#!/usr/bin/env node

const { spawnSync } = require("node:child_process");
const { mkdirSync, writeFileSync } = require("node:fs");
const { dirname, join, resolve } = require("node:path");

const projectRoot = resolve(__dirname, "..");
const demo = join(projectRoot, "scripts", "demo.cjs");
const outputPath = join(projectRoot, "docs", "assets", "demo.svg");
const result = spawnSync(process.execPath, [demo], {
  cwd: projectRoot,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "pipe"],
  timeout: 120_000,
  maxBuffer: 20 * 1024 * 1024
});

if (result.error) throw result.error;
if (result.status !== 0) {
  throw new Error(
    `Demo failed with ${String(result.status)}\n${result.stdout ?? ""}\n${result.stderr ?? ""}`
  );
}

const output = result.stdout ?? "";
const match = output.match(
  /=== A\.[^\n]+ ===\n\n(?<report>MergeReceipt v[\s\S]*?Verdict: PASS)\n/u
);
if (match?.groups?.report === undefined) {
  throw new Error("Could not find the clean scenario in demo output.");
}

const lines = match.groups.report.split("\n").map((line) => line.trimEnd());
const lineHeight = 24;
const top = 68;
const width = 760;
const height = top + lines.length * lineHeight + 36;
const text = lines
  .map((line, index) => {
    const y = top + index * lineHeight;
    const color = line.startsWith("✓")
      ? "#3fb950"
      : line === "Verdict: PASS"
        ? "#3fb950"
        : line.startsWith("•")
          ? "#8b949e"
          : "#e6edf3";
    return `  <text x="32" y="${String(y)}" fill="${color}">${escapeXml(line)}</text>`;
  })
  .join("\n");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${String(width)}" height="${String(height)}" viewBox="0 0 ${String(width)} ${String(height)}" role="img" aria-labelledby="title description">
  <title id="title">MergeReceipt clean verification report</title>
  <desc id="description">Actual terminal output generated by the production MergeReceipt CLI.</desc>
  <rect width="100%" height="100%" rx="12" fill="#0d1117"/>
  <circle cx="28" cy="26" r="6" fill="#ff5f56"/>
  <circle cx="48" cy="26" r="6" fill="#ffbd2e"/>
  <circle cx="68" cy="26" r="6" fill="#27c93f"/>
  <text x="380" y="31" text-anchor="middle" fill="#8b949e" font-size="13">npm run demo</text>
  <g font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="16">
${text}
  </g>
</svg>
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, svg, "utf8");
process.stdout.write(`Wrote ${outputPath}\n`);

function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}
